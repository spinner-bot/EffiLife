import { test, expect, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const list: string[] = []; errors.set(page, list)
  page.on('pageerror', error => list.push(error.message))
  page.on('console', message => { if (['error', 'warning'].includes(message.type())) list.push(message.text()) })
  await page.clock.setFixedTime(new Date('2026-11-11T10:00:00+08:00'))
})
test.afterEach(({ page }) => { expect(errors.get(page)).toEqual([]) })

test('manages pinned recurring checklists with search archive and retained history', async ({ page }, info) => {
  await page.goto('/#/todos')
  await page.getByRole('button', { name: '添加待办', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: '添加待办', exact: true })
  await dialog.getByLabel('名称', { exact: true }).fill('每周采购')
  for (const title of ['买盐', '买牛奶']) {
    await dialog.getByRole('textbox', { name: '添加检查项', exact: true }).fill(title)
    await dialog.getByRole('button', { name: '添加检查项', exact: true }).click()
  }
  await dialog.getByLabel('截止时间', { exact: false }).fill('2026-11-12T09:00')
  await dialog.locator('summary').click()
  await dialog.getByRole('combobox', { name: '重复安排', exact: true }).selectOption('week')
  await dialog.getByRole('checkbox', { name: '置顶', exact: true }).check()
  await dialog.getByLabel('标签', { exact: true }).fill('生活, 采购')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('textbox', { name: '有什么需要记住的？', exact: true }).fill('普通事项')
  await page.locator('.quick-capture').getByRole('button', { name: '添加待办' }).click()
  await expect(page.locator('.list-row').first()).toContainText('每周采购')
  await page.getByRole('searchbox', { name: '搜索', exact: true }).fill('牛奶')
  await expect(page.locator('.list-row')).toHaveCount(1)
  const row = page.locator('.list-row').first()
  const id = await row.getAttribute('data-todo-id')
  await row.locator('summary').click()
  await row.getByRole('checkbox', { name: '买牛奶', exact: true }).check()
  await expect(row.locator('summary')).toHaveText('检查项 1 / 2')
  await expect(row.getByRole('button', { name: '标记完成: 每周采购', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('searchbox', { name: '搜索', exact: true }).fill('')
  await page.locator('.todo-filter-panel summary').click()
  await page.getByRole('combobox', { name: '按标签筛选', exact: true }).selectOption('采购')
  await page.locator('.todo-filter-panel summary').click()
  await expect(page.locator('.list-row')).toHaveCount(1)
  await page.setViewportSize({ width: 390, height: 950 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await expect(page.locator('.toast')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('recurring-checklist-390.png'), fullPage: true })
  await row.getByRole('button', { name: '标记完成: 每周采购', exact: true }).click()
  await expect(page.locator('.list-row')).toHaveCount(1)
  await expect(page.locator('.list-row')).toContainText('11月19日')
  await expect(page.locator('.list-row').locator('summary')).toHaveText('检查项 0 / 2')
  await page.getByRole('button', { name: '已完成', exact: true }).click()
  await expect(page.locator('.list-row').locator('summary')).toHaveText('检查项 1 / 2')
  await page.getByRole('button', { name: '重新打开: 每周采购', exact: true }).click()
  await page.getByRole('button', { name: '待处理', exact: true }).click()
  await expect(page.locator('.list-row')).toHaveCount(2)
  await page.locator('[data-todo-id="' + id + '"]').getByRole('button', { name: '标记完成: 每周采购', exact: true }).click()
  await expect(page.locator('.list-row')).toHaveCount(1)
  await page.locator('.list-row').getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '归档', exact: true }).click()
  await page.getByRole('button', { name: '归档', exact: true }).click()
  await expect(page.locator('.list-row')).toHaveCount(1)
  await page.reload()
  await page.getByRole('button', { name: '归档', exact: true }).click()
  await expect(page.locator('.list-row')).toContainText('每周采购')
})

test('previews standalone legacy todo exports and keeps checklist and scheduling fields editable', async ({ page }) => {
  const data = { version: '0.5.0', categories: [{ id: 'home', name: '家务', color: '#526ac9' }], todos: [{ id: 'one', title: '旧版采购', description: '保留说明', created_at: '2026-11-01T00:00:00Z', category: 'home', status: 'in-progress', pinned: true, recurrence: 'weekly', tags: ['迁移'], subtasks: [{ id: 'salt', title: '买盐', completed: true }, { id: 'milk', title: '买牛奶', completed: false }] }] }
  await page.goto('/#/settings')
  await page.getByLabel('导入存档', { exact: true }).setInputFiles({ name: 'todos.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) })
  const preview = page.getByRole('dialog', { name: '检查即将导入的内容' })
  await expect(preview).toContainText('1 条待办')
  await preview.getByRole('button', { name: '确认替换并导入', exact: true }).click()
  await expect(preview).not.toBeVisible()
  await page.goto('/#/todos')
  await expect(page.locator('.list-row')).toContainText('进行中')
  await expect(page.locator('.list-row').locator('summary')).toHaveText('检查项 1 / 2')
  await page.locator('.list-row').getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑', exact: true })
  await expect(dialog.getByLabel('检查项名称 1', { exact: true })).toHaveValue('买盐')
  await dialog.locator('summary').click()
  await expect(dialog.getByRole('combobox', { name: '重复安排', exact: true })).toHaveValue('week')
  await expect(dialog.getByRole('checkbox', { name: '置顶', exact: true })).toBeChecked()
})

