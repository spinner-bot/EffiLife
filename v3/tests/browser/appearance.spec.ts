import { test, expect } from '@playwright/test'
test('changes material algorithms and advanced parameters per theme and restores defaults', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  page.on('console', entry => { if (['warning','error'].includes(entry.type())) errors.push(entry.text()) })
  await page.goto('/#/more/appearance')
  await page.getByRole('button', { name: '通透玻璃', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-surface-effect', 'glass')
  const trigger = page.getByRole('button', { name: '卡片高级设置', exact: true })
  await trigger.hover()
  await expect(trigger).toContainText('高级设置')
  await trigger.click()
  let dialog = page.getByRole('dialog', { name: '高级设置 · 浅色', exact: true })
  const blur = dialog.getByRole('slider', { name: '模糊度', exact: true })
  await blur.focus(); await blur.press('Home'); for (let i=0;i<5;i++) await blur.press('ArrowRight')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.panel').first()).toHaveCSS('backdrop-filter', /blur\(5px\)/)
  await page.reload()
  await expect(page.locator('.panel').first()).toHaveCSS('backdrop-filter', /blur\(5px\)/)
  await page.getByRole('button', { name: '卡片高级设置', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: '卡片外观', exact: true }).selectOption('frosted')
  await expect(dialog.getByRole('slider', { name: '饱和度', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('slider', { name: '主题染色', exact: true })).toBeVisible()
  await dialog.getByRole('checkbox', { name: '启用背景动画', exact: true }).uncheck()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.theme-decoration iframe')).toHaveCount(0)
  await page.getByRole('button', { name: '樱花', exact: true }).click()
  await expect(page.locator('.theme-decoration iframe')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('html')).toHaveAttribute('data-surface-effect', 'glass')
  await page.getByRole('button', { name: '主题高级设置', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('slider', { name: '粒子 / 图形密度', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '北欧极夜', exact: true }).click()
  await page.getByRole('button', { name: '主题高级设置', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('slider', { name: '粒子 / 图形密度', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('slider', { name: '动画速度', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '浅色', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-surface-effect', 'frosted')
  await expect(page.locator('.theme-decoration iframe')).toHaveCount(0)
  await page.getByRole('button', { name: '卡片高级设置', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '恢复主题默认', exact: true }).click()
  await expect(dialog.getByRole('slider', { name: '圆角半径', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-surface-effect', 'solid')
  await expect(page.locator('.theme-decoration iframe')).toHaveAttribute('data-ready', 'true')
  await page.screenshot({ path: info.outputPath('theme-materials-advanced.png'), fullPage: true })
  expect(errors).toEqual([])
})
test('renders an enriched quiet background and respects reduced motion', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/more/appearance')
  await page.getByRole('button', { name: '玻璃', exact: true }).click()
  const frame = page.locator('.theme-decoration iframe')
  await expect(frame).toHaveAttribute('data-ready', 'true')
  await page.goto('/')
  await page.screenshot({ path: info.outputPath('glass-overview-reduced-motion.png'), fullPage: true })
  const decoration = page.locator('.theme-decoration')
  const first = await decoration.screenshot()
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  expect(Buffer.compare(first, await decoration.screenshot())).toBe(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect.poll(async () => Buffer.compare(first, await decoration.screenshot())).not.toBe(0)
})
