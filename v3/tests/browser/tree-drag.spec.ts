import { test, expect, type Page } from '@playwright/test'
async function createPlan(page: Page) {
  await page.goto('/#/plans')
  await page.getByRole('button', { name: '新建计划', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill('结构调整')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('结构调整')
}
async function add(page: Page, title: string, kind: '分组' | '子项', parent?: string) {
  if (parent) {
    await page.locator('.tree-row').filter({ has: page.getByText(parent, { exact: true }) }).getByRole('button', { name: '更多操作', exact: true }).click()
    await page.getByRole('menuitem', { name: '添加' + kind, exact: true }).click()
  } else await page.getByRole('button', { name: '添加' + kind, exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill(title)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}
const row = (page: Page, title: string) => page.locator('[data-node-id]').filter({ has: page.getByText(title, { exact: true }) })
async function dragToGap(page: Page, title: string, xShift: number, targetY: number) {
  const handle = await row(page, title).locator('.drag-handle').boundingBox()
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + handle!.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle!.x + handle!.width / 2 + xShift, targetY, { steps: 16 })
}
test('moves whole groups and selects ambiguous gap depth horizontally without extra save steps', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await createPlan(page)
  await add(page, '外组', '分组'); await add(page, '条目一', '子项', '外组')
  await add(page, '内组', '分组', '外组'); await add(page, '条目二', '子项', '内组')
  await add(page, '条目三', '子项')
  const two = await row(page, '条目二').boundingBox()
  await dragToGap(page, '条目三', 48, two!.y + two!.height + 3)
  await expect(page.locator('.tree-drop-gap')).toHaveAttribute('data-depth', '2')
  await expect(page.locator('.tree-drop-gap')).toContainText('内组')
  await page.mouse.up()
  await expect(row(page, '条目三')).toHaveAttribute('data-depth', '2')
  await dragToGap(page, '条目三', -48, two!.y + two!.height + 3)
  await expect(page.locator('.tree-drop-gap')).toHaveAttribute('data-depth', '0')
  await page.mouse.up()
  await expect(row(page, '条目三')).toHaveAttribute('data-depth', '0')
  const outer = await row(page, '外组').boundingBox()
  await dragToGap(page, '内组', -24, outer!.y + 2)
  await expect(page.locator('.tree-drag-ghost')).toContainText('1 个节点')
  await expect(page.locator('[data-tree-row]').filter({ has: page.getByText('条目二', { exact: true }) })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('subtree-drop-preview.png'), fullPage: true })
  await page.mouse.up()
  await expect(row(page, '内组')).toHaveAttribute('data-depth', '0')
  await expect(row(page, '条目二')).toHaveAttribute('data-depth', '1')
  await expect(page.locator('.tree-row .row-title')).toHaveText(['内组','生活条目二','外组','生活条目一','生活条目三'])
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(row(page, '条目二')).toHaveAttribute('data-depth', '1')
  await expect(page.locator('.tree-row .row-title').first()).toHaveText('内组')
  expect(errors).toEqual([])
})
test.describe('touch dragging', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 1100 } })
  test('uses real touch events to indent a task and saves immediately', async ({ page, context }) => {
    await createPlan(page); await add(page, '手势分组', '分组'); await add(page, '手势子项', '子项')
    await row(page, '手势子项').scrollIntoViewIfNeeded()
    const box = await row(page, '手势子项').locator('.drag-handle').boundingBox()
    const client = await context.newCDPSession(page)
    const x = box!.x + box!.width / 2, y = box!.y + box!.height / 2
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    for (let step = 1; step <= 10; step++) await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 22 * step / 10, y: y + 10 * step / 10 }] })
    await expect(page.locator('.tree-drop-gap')).toHaveAttribute('data-depth', '1')
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(row(page, '手势子项')).toHaveAttribute('data-depth', '1')
    await page.reload()
    await expect(row(page, '手势子项')).toHaveAttribute('data-depth', '1')
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  })
})
