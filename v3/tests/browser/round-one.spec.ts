import { test, expect } from '@playwright/test'

test('creates categories in place and inherits plan and group defaults after reload', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/plans')
  await page.getByRole('button', { name: '新建计划', exact: true }).first().click()
  const plan = page.getByRole('dialog', { name: '开始一份主题计划' })
  await plan.getByLabel('名称', { exact: true }).fill('旅行计划')
  await plan.getByLabel('背景时间类别', { exact: true }).selectOption('__create__')
  const category = page.getByRole('dialog', { name: '新增类别', exact: true })
  await category.getByLabel('名称', { exact: true }).fill('出行')
  await category.getByRole('button', { name: '保存', exact: true }).click()
  await expect(plan.getByLabel('名称', { exact: true })).toHaveValue('旅行计划')
  await expect(plan.getByLabel('背景时间类别', { exact: true }).locator('option:checked')).toHaveText('出行')
  await plan.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('旅行计划')
  await page.getByRole('button', { name: '添加子项', exact: true }).first().click()
  const task = page.getByRole('dialog', { name: '添加子项', exact: true })
  await task.getByLabel('名称', { exact: true }).fill('买车票')
  await task.getByRole('button', { name: '保存', exact: true }).click()
  const row = page.locator('.tree-row').filter({ hasText: '买车票' })
  await expect(row.locator('.category-badge')).toHaveText('出行')
  await expect(row).not.toContainText('A1')
  await page.reload()
  await expect(row.locator('.category-badge')).toHaveText('出行')
  await page.screenshot({ path: info.outputPath('plan-category-default.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('manages allocation templates and reorders rules while the fallback stays fixed', async ({ page }, info) => {
  await page.goto('/#/more')
  await expect(page.locator('.more-entry').last()).toContainText('设置')
  await page.getByRole('link', { name: /分配方案管理/ }).click()
  for (const name of ['普通工作日', '休息日']) {
    await page.getByRole('button', { name: '新建分配方案', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '新建分配方案', exact: true })
    await dialog.getByLabel('名称', { exact: true }).fill(name)
    await dialog.getByRole('button', { name: '什么是其他日期的默认方案？', exact: true }).click()
    const help = page.getByRole('dialog', { name: '什么是其他日期的默认方案？', exact: true })
    await expect(help).toContainText('不会覆盖已有的日期指定')
    await help.getByRole('button', { name: '关闭', exact: true }).last().click()
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  await page.goto('/#/more/rules')
  for (const name of ['普通工作日', '休息日']) {
    await page.getByRole('button', { name: '添加重复日期规则', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: '分配方案', exact: true }).selectOption({ label: name })
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  const rows = page.locator('.sortable-row')
  await expect(rows).toHaveCount(2)
  await expect(rows.first()).toContainText('普通工作日')
  const handle = await rows.last().locator('.drag-handle').boundingBox()
  const first = await rows.first().boundingBox()
  await page.mouse.move(handle!.x + 10, handle!.y + 10)
  await page.mouse.down()
  await page.mouse.move(handle!.x + 10, first!.y + 4, { steps: 14 })
  await expect(page.locator('.sort-gap')).toBeVisible()
  await page.mouse.up()
  await expect(rows.first()).toContainText('休息日')
  await expect(page.locator('.fallback-rule')).toContainText('普通工作日')
  await expect(page.locator('.fallback-rule .drag-handle')).toHaveCount(0)
  await page.reload()
  await expect(rows.first()).toContainText('休息日')
  await page.screenshot({ path: info.outputPath('schedule-rules.png'), fullPage: true })
  await page.goto('/#/time?date=2026-11-11')
  const panel = page.locator('.panel').filter({ has: page.getByRole('heading', { name: '分配方案', exact: true }) })
  await expect(panel.getByRole('combobox')).toHaveCount(0)
  await panel.getByRole('button', { name: '更多操作' }).click()
  await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '修改日程方案', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '修改日程方案', exact: true })).toBeVisible()
})
