import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  errors.set(page, [])
  page.on('pageerror', error => errors.get(page)!.push(error.message))
  page.on('console', entry => { if (['warning', 'error'].includes(entry.type())) errors.get(page)!.push(entry.text()) })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

for (const [zone, date] of [['America/Santiago', '2026-09-06'], ['America/Havana', '2026-03-08']]) {
  test.describe(zone!, () => {
    test.use({ timezoneId: zone })
    test('opens the DST midnight day and saves its time plan', async ({ page }) => {
      await page.clock.install({ time: new Date(date + 'T12:00:00Z') })
      await page.goto('/')
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('让每一份投入，都有迹可循。')
      await page.goto('/#/time?date=' + date)
      await page.getByRole('button', { name: '新建分配方案', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: '新建分配方案', exact: true })
      await dialog.getByLabel('名称', { exact: true }).fill('DST 日方案')
      await dialog.getByRole('button', { name: '保存', exact: true }).click()
      await expect(dialog).not.toBeVisible()
      await expect(page.getByRole('heading', { name: 'DST 日方案', exact: true })).toBeVisible()
      await page.reload()
      await expect(page.getByRole('heading', { name: 'DST 日方案', exact: true })).toBeVisible()
    })
  })
}

test('keeps a metadata-edited built-in category localized but preserves a custom rename', async ({ page }) => {
  await page.goto('/#/settings')
  await page.getByRole('button', { name: '编辑: 工作', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '编辑', exact: true })
  await dialog.getByRole('spinbutton').fill('8')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('combobox', { name: '语言', exact: true }).selectOption('en-US')
  await expect(page.getByRole('button', { name: 'Edit: Work', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit: Work', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Edit', exact: true })
  await dialog.getByRole('textbox', { name: 'Title', exact: true }).fill('我的工作')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('zh-CN')
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑: 我的工作', exact: true })).toBeVisible()
})

test('editing a template leaves an automatic date free to follow later calendar rules', async ({ page }) => {
  await page.goto('/#/time?date=2026-11-11')
  await page.getByRole('button', { name: '新建分配方案', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill('原默认方案')
  await dialog.getByLabel('设为其他日期的默认方案', { exact: true }).check()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.goto('/#/time?date=2026-11-12')
  const panel = page.locator('.panel').filter({ has: page.getByRole('heading', { name: '分配方案', exact: true }) })
  await panel.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '编辑分配方案', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('同时将此方案指定给当前日期', { exact: true })).not.toBeChecked()
  await dialog.getByLabel('名称', { exact: true }).fill('编辑后的原方案')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await panel.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '新建分配方案', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill('新默认方案')
  await dialog.getByLabel('设为其他日期的默认方案', { exact: true }).check()
  await dialog.getByLabel('同时将此方案指定给当前日期', { exact: true }).uncheck()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(panel.getByRole('heading', { name: '新默认方案', exact: true })).toBeVisible()
  await page.goto('/#/time?date=2026-11-11')
  await expect(panel.getByRole('heading', { name: '编辑后的原方案', exact: true })).toBeVisible()
})

test('previews invalid legacy wall times and deletes a migrated task without losing its todo', async ({ page }) => {
  await page.goto('/#/settings')
  await page.getByLabel('时区', { exact: true }).fill('America/Santiago')
  await page.getByLabel('时区', { exact: true }).press('Tab')
  const source = {
    records: { '2026-09-06': [{ start: '00:30', end: '00:45', content: '不存在的时间' }, { start: '01:00', end: '01:30', content: '真实有效记录' }] },
    planHelper: { plans: [{ head: { index: 7, name: '迁移计划', date: [2026, 9, 6] }, main: [{ name: '章节', plan: [null, { content: '可删除任务', is_active: true }] }], log: [] }] },
    todos: [{ id: 'related', title: '保留的待办', created_at: '2026-09-06T04:00:00Z', related_plan_id: 7, related_plan_task_id: 'A1' }],
  }
  await page.getByLabel('导入存档', { exact: true }).setInputFiles({ name: 'legacy-review.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(source)) })
  let dialog = page.getByRole('dialog', { name: '检查即将导入的内容' })
  await expect(dialog.getByText(/部分旧时间在所选时区不存在或无效/)).toBeVisible()
  await dialog.getByRole('button', { name: '确认替换并导入', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.goto('/#/time?date=2026-09-06')
  await expect(page.locator('.list-row')).toHaveCount(1)
  await expect(page.locator('.list-row')).toContainText('真实有效记录')
  await page.goto('/#/plans')
  await page.getByRole('link', { name: /迁移计划/ }).click()
  await page.getByRole('button', { name: '更多操作', exact: true }).first().click()
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('相关待办会保留')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('可删除任务', { exact: true })).not.toBeVisible()
  await page.goto('/#/todos')
  await expect(page.locator('.list-row')).toContainText('保留的待办')
  await page.reload()
  await expect(page.locator('.list-row')).toContainText('保留的待办')
})
